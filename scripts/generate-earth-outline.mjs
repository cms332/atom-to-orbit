import { writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';

// Build-time only. Natural Earth is public domain; D3 (ISC) is not shipped to the browser.
const source =
	'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const response = await fetch(source);
if (!response.ok) throw new Error(`Natural Earth: ${response.status}`);
const original = await response.text();
await writeFile('docs/reference-assets/ne_110m_land.geojson', original);
const d3Response = await fetch('https://cdn.jsdelivr.net/npm/d3@7.9.0/dist/d3.min.js');
if (!d3Response.ok) throw new Error(`D3: ${d3Response.status}`);
const context = {};
runInNewContext(await d3Response.text(), context);
const projection = context.d3
	.geoOrthographic()
	.rotate([-20, -15])
	.translate([50, 50])
	.scale(50)
	.precision(0.1);
const path = context.d3.geoPath(projection).digits(2)(JSON.parse(original));
await writeFile(
	'src/lib/data/earth-outline.ts',
	`// Natural Earth 1:110m land, public domain. Generated by scripts/generate-earth-outline.mjs.\n// Orthographic view centred on 20 E, 15 N; 100-unit diameter.\nexport const earthLandPath = ${JSON.stringify(path)};\n`
);
console.log(`Generated ${path.length} characters of projected coastline.`);
